import type { Metadata } from "next";
import { site } from "@/content/site";

const defaultTitle = "High quality content for real estate agencies";

/**
 * Site-wide metadata defaults (App Router Metadata API).
 * Subpages override `title`, `description`, and `alternates.canonical`.
 */
export const defaultMetadata: Metadata = {
  metadataBase: new URL(site.url),
  title: {
    default: defaultTitle,
    template: `%s | ${site.name}`,
  },
  description: site.description,
  keywords: [
    "real estate content Dubai",
    "property video from photos",
    "real estate reels Dubai",
    "listing videos",
    "real estate social media management Dubai",
    "property marketing content",
  ],
  authors: [{ name: site.name }],
  creator: site.name,
  alternates: {
    canonical: "/",
  },
  // og:title/og:description/twitter:* deliberately omit title/description so
  // they fall back to each page's own resolved metadata (subpages would
  // otherwise inherit the homepage values wholesale). The branded OG image is
  // generated by app/opengraph-image.tsx and attached automatically.
  openGraph: {
    type: "website",
    locale: "en_US",
    siteName: site.name,
  },
  twitter: {
    card: "summary_large_image",
  },
  // No `robots` block: index+follow is already the crawler default, and an
  // explicit tag here would conflict with the automatic noindex on /not-found.
};
